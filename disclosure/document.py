"""Filing documents: raw EDGAR HTML to clean blocks, with 10-K and 10-Q sections detected.

EDGAR HTML is generated by a dozen different filing agents and carries
inline XBRL, hidden fact headers, spacer cells and page furniture. The
reader needs something much simpler: a list of paragraphs and tables with
bold and italic preserved, and the position of each Item heading. Risk
factor comparison, filing diffs and full-text excerpts all work from the
same blocks, so a filing is parsed once and cached.
"""
from __future__ import annotations

import re
from dataclasses import asdict, dataclass

from lxml import etree
from lxml import html as lh

from . import sec
from .sec import DAY
from .store import memoize

BLOCK_TAGS = {"p", "div", "table", "h1", "h2", "h3", "h4", "h5", "h6", "li", "ul", "ol", "center", "blockquote", "section", "article", "body", "dl", "dt", "dd", "pre", "form"}
DROP_TAGS = {"script", "style", "head", "title", "meta", "link", "noscript", "ix:header", "img", "object", "iframe"}
WS = re.compile(r"[\s ​   ]+")
NUMERIC = re.compile(r"^[\$\(\-–—\s]*[\d,]*\.?\d+\s*\)?\s*%?\)?$|^[—–-]+$")
PAGE_NO = re.compile(r"^(page\s*)?[ivxlc\d]{1,4}$|^table of contents$|^index$|^\d+\s*\|\s*.{0,60}$", re.I)
ITEM = re.compile(r"^\s*item\s*(\d{1,2}[a-d]?)\s*[\.:\-–—]?\s*(.{0,160})$", re.I)
PART = re.compile(r"^\s*part\s+(iv|iii|ii|i)\b", re.I)
NOTE = re.compile(r"^\s*(?:note\s+(\d{1,2}|[a-z])\b|(\d{1,2})\s*[\.\-–—:]\s+[A-Z])", re.I)

TITLES_10K = {
    "1": "Business", "1A": "Risk factors", "1B": "Unresolved staff comments", "1C": "Cybersecurity", "2": "Properties",
    "3": "Legal proceedings", "4": "Mine safety disclosures", "5": "Market for the company's equity", "6": "Reserved",
    "7": "Management's discussion and analysis", "7A": "Market risk", "8": "Financial statements and notes",
    "9": "Changes in accountants", "9A": "Controls and procedures", "9B": "Other information",
    "9C": "Foreign jurisdictions that prevent inspections", "10": "Directors and executive officers", "11": "Executive compensation",
    "12": "Security ownership", "13": "Relationships and director independence", "14": "Principal accountant fees",
    "15": "Exhibits and schedules", "16": "Form 10-K summary",
}
TITLES_10Q = {
    "I-1": "Financial statements and notes", "I-2": "Management's discussion and analysis", "I-3": "Market risk",
    "I-4": "Controls and procedures", "II-1": "Legal proceedings", "II-1A": "Risk factors",
    "II-2": "Unregistered sales and share repurchases", "II-3": "Defaults on senior securities", "II-4": "Mine safety disclosures",
    "II-5": "Other information", "II-6": "Exhibits",
}


@dataclass
class Block:
    kind: str  # "p" or "table"
    html: str
    text: str
    bold: bool = False
    italic: bool = False
    center: bool = False


# ---------------------------------------------------------------- styles
def _style(el) -> str:
    return (el.get("style") or "").lower().replace(" ", "")


def _is_bold(el) -> bool:
    s = _style(el)
    return el.tag in ("b", "strong") or "font-weight:bold" in s or "font-weight:700" in s or "font-weight:600" in s or "font-weight:800" in s


def _is_italic(el) -> bool:
    return el.tag in ("i", "em") or "font-style:italic" in _style(el)


def _hidden(el) -> bool:
    s = _style(el)
    return "display:none" in s or "visibility:hidden" in s


def _indent(el) -> int:
    m = re.search(r"(?:padding-left|margin-left|text-indent):(\d+(?:\.\d+)?)(pt|px|em|in)", _style(el))
    if not m:
        return 0
    v = float(m[1]) * {"pt": 1, "px": 0.75, "em": 10, "in": 72}[m[2]]
    return 2 if v >= 18 else 1 if v >= 7 else 0


def _esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


# ---------------------------------------------------------------- inline content
def _inline(el, bold=False, italic=False) -> list[tuple[str, bool, bool, bool]]:
    """Flatten an element into (text, bold, italic, superscript) runs."""
    runs: list[tuple[str, bool, bool, bool]] = []
    tag = el.tag if isinstance(el.tag, str) else ""
    if tag in DROP_TAGS or _hidden(el):
        return runs
    b, i = bold or _is_bold(el), italic or _is_italic(el)
    sup = tag == "sup"
    if tag == "br":
        runs.append(("\n", b, i, False))
    if el.text and tag != "br":
        runs.append((el.text, b, i, sup))
    for child in el:
        if isinstance(child.tag, str):
            runs += _inline(child, b, i)
        if child.tail:
            runs.append((child.tail, b, i, False))
    return runs


def _render_runs(runs) -> tuple[str, str, bool, bool]:
    """Runs to (html, plain text, all bold, all italic), merging neighbours with the same style."""
    parts, text = [], []
    merged: list[list] = []
    for t, b, i, s in runs:
        t = t.replace("\n", " ") if t != "\n" else " "
        t = WS.sub(" ", t)
        if not t:
            continue
        if merged and merged[-1][1:] == [b, i, s]:
            merged[-1][0] += t
        else:
            merged.append([t, b, i, s])
    visible = [m for m in merged if m[0].strip()]
    all_b = bool(visible) and all(m[1] for m in visible)
    all_i = bool(visible) and all(m[2] for m in visible)
    for t, b, i, s in merged:
        h = _esc(t)
        if s:
            h = f"<sup>{h.strip()}</sup>"
        if i and not all_i and t.strip():
            h = f"<i>{h}</i>"
        if b and not all_b and t.strip():
            h = f"<b>{h}</b>"
        parts.append(h)
        text.append(t)
    return "".join(parts).strip(), "".join(text).strip(), all_b, all_i


# ---------------------------------------------------------------- tables
def _table(el) -> Block | None:
    rows = []
    for tr in el.iter("tr"):
        if _hidden(tr):
            continue
        cells, col = [], 0
        for td in tr:
            if not isinstance(td.tag, str) or td.tag not in ("td", "th"):
                continue
            span = int(td.get("colspan") or 1) if (td.get("colspan") or "1").isdigit() else 1
            h, t, b, _ = _render_runs(_inline(td))
            cells.append({"col": col, "span": max(1, span), "html": h, "text": t, "bold": b or td.tag == "th", "indent": _indent(td) or _indent(td[0]) if len(td) else _indent(td)})
            col += max(1, span)
        rows.append(cells)
    if not rows:
        return None

    # Currency signs, closing parentheses and percent signs often sit in their own cells.
    for cells in rows:
        filled = [c for c in cells if c["text"]]
        for k, c in enumerate(filled):
            if c["text"] in ("$", "(", "$(") and k + 1 < len(filled):
                nxt = filled[k + 1]
                nxt["text"], nxt["html"] = c["text"] + nxt["text"], _esc(c["text"]) + nxt["html"]
                c["text"] = c["html"] = ""
            elif c["text"] in (")", "%", ")%", "%)", "pts", "bps") and k > 0:
                prv = next((p for p in reversed(filled[:k]) if p["text"]), None)
                if prv:
                    prv["text"] += c["text"] if c["text"] not in ("pts", "bps") else " " + c["text"]
                    prv["html"] += _esc(c["text"]) if c["text"] not in ("pts", "bps") else " " + c["text"]
                    c["text"] = c["html"] = ""

    rows = [r for r in rows if any(c["text"] for c in r)]
    if not rows:
        return None
    used = sorted({c["col"] for r in rows for c in r if c["text"]})
    if len(rows) == 1 and len([c for c in rows[0] if c["text"]]) <= 3:
        # One-row layout tables are usually headings ("Item 1A." | "Risk Factors") or bullets.
        filled = [c for c in rows[0] if c["text"]]
        text = " ".join(c["text"] for c in filled)
        if len(filled) == 2 and filled[0]["text"] in ("•", "●", "◦", "▪", "·", "-", "–", "o"):
            return Block("p", f'<span class="bullet">•</span> {filled[1]["html"]}', filled[1]["text"])
        return Block("p", " ".join(c["html"] for c in filled), text, all(c["bold"] for c in filled))

    pos = {c: k for k, c in enumerate(used)}
    ncol = len(used)
    out, plain = [], []
    for r in rows:
        line, cursor, texts = [], 0, []
        row_bold = all(c["bold"] for c in r if c["text"])
        for c in r:
            covered = [pos[x] for x in range(c["col"], c["col"] + c["span"]) if x in pos]
            if not covered:
                continue
            start, span = covered[0], len(covered)
            if start < cursor:
                continue
            if start > cursor:
                line.append(f'<td colspan="{start - cursor}"></td>' if start - cursor > 1 else "<td></td>")
            cls = []
            if c["text"] and NUMERIC.match(c["text"]):
                cls.append("n")
            if c["bold"] and not row_bold:
                cls.append("b")
            if c["indent"]:
                cls.append(f"in{c['indent']}")
            attr = (f' colspan="{span}"' if span > 1 else "") + (f' class="{" ".join(cls)}"' if cls else "")
            line.append(f"<td{attr}>{c['html']}</td>")
            cursor = start + span
            if c["text"]:
                texts.append(c["text"])
        if cursor < ncol:
            line.append(f'<td colspan="{ncol - cursor}"></td>' if ncol - cursor > 1 else "<td></td>")
        out.append(("<tr class=\"b\">" if row_bold else "<tr>") + "".join(line) + "</tr>")
        plain.append(" | ".join(texts))
    return Block("table", f'<table class="ft">{"".join(out)}</table>', "\n".join(plain))


# ---------------------------------------------------------------- blocks
def _blocks(root) -> list[Block]:
    blocks: list[Block] = []
    pending: list = []

    def flush(center=False):
        if not pending:
            return
        h, t, b, i = _render_runs(pending)
        pending.clear()
        if not t or PAGE_NO.match(t):
            return
        blocks.append(Block("p", h, t, b, i, center))

    def has_block_child(el) -> bool:
        return any(isinstance(c.tag, str) and (c.tag in BLOCK_TAGS or c.tag == "hr") for c in el.iterdescendants())

    def walk(el):
        tag = el.tag if isinstance(el.tag, str) else ""
        if not tag or tag in DROP_TAGS or _hidden(el):
            return
        if tag == "table":
            flush()
            b = _table(el)
            if b:
                blocks.append(b)
            return
        if tag == "hr":
            flush()
            return
        center = el.get("align") == "center" or "text-align:center" in _style(el) or tag == "center"
        if tag in BLOCK_TAGS and not has_block_child(el):
            flush()
            pending.extend(_inline(el))
            if tag in ("li",):
                pending.insert(0, ("• ", False, False, False))
            flush(center)
            return
        if tag in BLOCK_TAGS:
            flush()
        b, i = _is_bold(el), _is_italic(el)
        if el.text:
            pending.append((el.text, b, i, False))
        for child in el:
            if isinstance(child.tag, str):
                if child.tag in BLOCK_TAGS or child.tag in ("table", "hr") or has_block_child(child):
                    walk(child)
                else:
                    pending.extend(_inline(child, b, i))
            if child.tail:
                pending.append((child.tail, b, i, False))
        if tag in BLOCK_TAGS:
            flush(center)

    walk(root)
    flush()
    return _tidy(blocks)


BULLETS = {"•", "●", "◦", "▪", "·", "-", "–", "o", "•", "●", "▪", "", ""}


def _tidy(blocks: list[Block]) -> list[Block]:
    """Drop running page headers and join bullet characters to the text they introduce."""
    counts: dict[str, int] = {}
    for b in blocks:
        if b.kind == "p" and len(b.text) < 60:
            counts[b.text] = counts.get(b.text, 0) + 1
    # A short line repeated on many pages ("PART II", "Item 7", the company name) is a page header.
    repeated = {t for t, n in counts.items() if n >= 5}
    out: list[Block] = []
    k = 0
    while k < len(blocks):
        b = blocks[k]
        if b.kind == "p" and b.text in repeated:
            k += 1
            continue
        if b.kind == "p" and b.text in BULLETS and k + 1 < len(blocks) and blocks[k + 1].kind == "p":
            nxt = blocks[k + 1]
            out.append(Block("p", f'<span class="bullet">•</span> {nxt.html}', nxt.text, nxt.bold, nxt.italic))
            k += 2
            continue
        out.append(b)
        k += 1
    return out


def _clean_tags(root) -> None:
    """Inline XBRL wraps numbers in ix: elements; keep their content, drop the hidden header."""
    for el in list(root.iter()):
        if not isinstance(el.tag, str):
            continue
        tag = el.tag.lower()
        if tag.startswith("{"):
            tag = tag.split("}", 1)[1]
        el.tag = tag.split(":")[-1] if tag.startswith("ix:") and tag != "ix:header" else tag


# ---------------------------------------------------------------- sections
def _heading(b: Block) -> bool:
    return b.kind == "p" and len(b.text) < 200 and (b.bold or b.text.isupper() or b.center)


def sections(blocks: list[Block], form: str) -> tuple[list[dict], list[dict]]:
    """Locate Item headings, skipping the table of contents, and the notes to the financial statements."""
    quarterly = form.startswith("10-Q")
    part = "I"
    cands = []
    for k, b in enumerate(blocks):
        if b.kind != "p" or len(b.text) > 220:
            continue
        pm = PART.match(b.text)
        if pm and len(b.text) < 120:
            part = pm[1].upper()
        m = ITEM.match(b.text)
        if not m:
            continue
        num = m[1].upper()
        key = f"{part}-{num}" if quarterly else num
        cands.append((k, key, m[2].strip(" .:-–—")))
    if not cands:
        return [], []
    # The same heading appears in the table of contents and sometimes in page headers. Prefer
    # headings that carry a title, and among those the one followed by the most text before a
    # different Item begins.
    size = []
    for n, (k, key, _) in enumerate(cands):
        end = next((cands[j][0] for j in range(n + 1, len(cands)) if cands[j][1] != key), len(blocks))
        size.append(sum(len(blocks[j].text) for j in range(k, end)))
    best: dict[str, int] = {}
    for n, (_, key, title) in enumerate(cands):
        cur = best.get(key)
        if cur is None or (bool(title), size[n]) > (bool(cands[cur][2]), size[cur]):
            best[key] = n
    titles = TITLES_10Q if quarterly else TITLES_10K
    found = sorted(best.values(), key=lambda n: cands[n][0])
    out = []
    for n in found:
        k, key, own = cands[n]
        title = titles.get(key) or (own[:1].upper() + own[1:].lower() if own else f"Item {key}")
        label = f"Item {key.split('-')[-1]}"
        if quarterly:
            label = f"Part {key.split('-')[0]}, {label}"
        out.append({"key": key, "label": label, "title": title, "block": k})

    notes = []
    fs = next((s for s in out if s["key"] in ("8", "I-1")), None)
    if fs:
        nxt = next((s["block"] for s in out if s["block"] > fs["block"]), len(blocks))
        if nxt - fs["block"] < 30:
            # Item 8 only points to financial statements printed after Item 15 (NVIDIA, JPMorgan).
            nxt = len(blocks)
        for k in range(fs["block"] + 1, nxt):
            b = blocks[k]
            if _heading(b) and NOTE.match(b.text) and len(b.text) < 140:
                notes.append({"title": b.text, "block": k, "segment": "segment" in b.text.lower()})
    return out, notes


# ---------------------------------------------------------------- entry points
def parse(raw: str) -> list[Block]:
    raw = re.sub(r"^\s*<\?xml[^>]*>", "", raw)
    root = lh.document_fromstring(raw)
    _clean_tags(root)
    body = root.find("body")
    return _blocks(body if body is not None else root)


def plain_document(raw: str) -> list[Block]:
    """Pre-2001 filings and some exhibits are plain text."""
    paras = [p.strip() for p in re.split(r"\n\s*\n", raw) if p.strip()]
    return [Block("p", f"<pre>{_esc(p)}</pre>", WS.sub(" ", p)) for p in paras]


async def documents(cik: int, accession: str) -> list[dict]:
    """Documents in a filing, from its EDGAR index page."""
    page = await sec.get_text(sec.archive_url(cik, accession, f"{accession}-index.htm"), DAY * 30)
    root = lh.document_fromstring(page)
    out = []
    for tr in root.xpath("//table[contains(@class,'tableFile')][1]//tr[td]"):
        tds = tr.findall("td")
        if len(tds) < 5:
            continue
        a = tds[2].find(".//a")
        if a is None:
            continue
        href = a.get("href", "")
        name = href.rsplit("/", 1)[-1]
        if href.startswith("/ix?doc="):
            href = href[len("/ix?doc="):]
        out.append({"seq": tds[0].text_content().strip(), "description": tds[1].text_content().strip(), "name": name,
                    "path": href.split(f"/{accession.replace('-', '')}/", 1)[-1], "type": tds[3].text_content().strip(),
                    "size": tds[4].text_content().strip()})
    return out


@memoize("doc:v6", DAY * 30)
async def load(cik: int, accession: str, path: str) -> dict:
    """Parsed blocks for one document of a filing. Filings never change, so this is cached for a month."""
    url = sec.archive_url(cik, accession, path)
    lower = path.lower()
    if lower.endswith(".pdf"):
        return {"blocks": [], "url": url, "unsupported": "PDF"}
    raw = await sec.get_text(url, DAY * 30)
    if lower.endswith(".txt"):
        blocks = plain_document(raw)
    else:
        try:
            blocks = parse(raw)
        except (etree.ParserError, ValueError):
            blocks = plain_document(re.sub(r"<[^>]+>", " ", raw))
    return {"blocks": [asdict(b) for b in blocks], "url": url}


def restore(blocks: list[dict]) -> list[Block]:
    return [Block(**b) for b in blocks]
